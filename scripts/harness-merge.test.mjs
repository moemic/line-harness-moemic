import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { resolveLineWebhookConflicts, mergeLineRelease } from './harness-merge.mjs';

const root = mkdtempSync(resolve(tmpdir(), 'line-merge-test-'));
const path = resolve(root, 'apps/worker/src/routes/webhook.ts');
mkdirSync(resolve(root, 'apps/worker/src/routes'), { recursive: true });
const env = { ...process.env };
for (const key of ['GH_TOKEN', 'CLOUDFLARE_API_TOKEN', 'VERCEL_TOKEN']) delete env[key];
const git = args => execFileSync('git', args, { cwd: root, env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
const commit = message => git(['-c', 'commit.gpgsign=false', 'commit', '-am', message]);
git(['init', '-b', 'main']);
git(['config', 'user.name', 'Fixture']);
git(['config', 'user.email', 'fixture@example.invalid']);
const base = 'async function deliver() {\n  await handleEvent(\n    proxyDispatch,\n  );\n}\n' + Array.from({ length: 20 }, (_, i) => `// context ${i}\n`).join('') + 'async function handleEvent(\n  proxyDispatch?: HarnessProxyDispatch,\n): Promise<void> {}\n';
writeFileSync(path, base);
mkdirSync(resolve(root, '.github/workflows'), { recursive: true });
writeFileSync(resolve(root, '.github/workflows/custom.yml'), 'keep existing CI\n');
git(['add', '.']);
commit('base');
const baseSha = git(['rev-parse', 'HEAD']);
git(['checkout', '-b', 'installed']);
writeFileSync(path, base.replace('    proxyDispatch,', '    proxyDispatch,\n    c.env.AI_BRIDGE_URL,').replace('  proxyDispatch?: HarnessProxyDispatch,', '  proxyDispatch?: HarnessProxyDispatch,\n  aiBridgeUrl?: string,'));
commit('preserve bridge');
const installedSha = git(['rev-parse', 'HEAD']);
git(['checkout', '-b', 'official', baseSha]);
writeFileSync(path, base.replace('    proxyDispatch,', '    proxyDispatch,\n    c.env,').replace('  proxyDispatch?: HarnessProxyDispatch,', "  proxyDispatch?: HarnessProxyDispatch,\n  gateEnv?: Env['Bindings'],"));
writeFileSync(resolve(root, '.github/workflows/custom.yml'), 'unrequested upstream CI change\n');
commit('official gate');
const officialSha = git(['rev-parse', 'HEAD']);
git(['checkout', 'installed']);
const merge = spawnSync('git', ['merge', '--no-edit', 'official'], { cwd: root, env, encoding: 'utf8' });
assert.equal(merge.status, 1);
assert.equal(git(['diff', '--name-only', '--diff-filter=U']), 'apps/worker/src/routes/webhook.ts');
const conflict = readFileSync(path, 'utf8');
const merged = resolveLineWebhookConflicts(conflict);
assert.match(merged, /c\.env\.AI_BRIDGE_URL,\n\s+c\.env,/);
assert.match(merged, /aiBridgeUrl\?: string,\n\s+gateEnv\?: Env\['Bindings'\],/);
assert.throws(() => resolveLineWebhookConflicts(conflict.replace('c.env.AI_BRIDGE_URL,', 'c.env.UNKNOWN,')), /未知/);
assert.throws(() => resolveLineWebhookConflicts(base), /2箇所/);
writeFileSync(path, merged);
git(['add', '.']);
commit('resolve preserving both');
git(['checkout', 'official']);
writeFileSync(resolve(root, 'next-release.txt'), 'next compatible release\n');
git(['add', '.']);
commit('next official stable');
const nextOfficialSha = git(['rev-parse', 'HEAD']);
git(['checkout', 'installed']);
git(['merge', '--no-edit', 'official']);
assert.equal(readFileSync(path, 'utf8'), merged);
assert.equal(readFileSync(resolve(root, 'next-release.txt'), 'utf8'), 'next compatible release\n');
console.log('実Git競合2箇所・未知競合拒否・次の互換リリース追従の回帰試験成功');

// 上流のworkflow変更を導入せず、次版も記録済み公式baseから三者比較する。
git(['checkout', '-b', 'source-snapshot', installedSha]);
await mergeLineRelease(root, baseSha, officialSha);
assert.equal(readFileSync(resolve(root, '.github/workflows/custom.yml'), 'utf8'), 'keep existing CI\n');
assert.equal(readFileSync(path, 'utf8'), merged);
assert.equal(git(['rev-parse', 'HEAD^']), installedSha);
assert.equal(spawnSync('git', ['merge-base', '--is-ancestor', officialSha, 'HEAD'], { cwd: root, env }).status, 1);
await mergeLineRelease(root, officialSha, nextOfficialSha);
assert.equal(readFileSync(path, 'utf8'), merged);
assert.equal(readFileSync(resolve(root, '.github/workflows/custom.yml'), 'utf8'), 'keep existing CI\n');
assert.equal(readFileSync(resolve(root, 'next-release.txt'), 'utf8'), 'next compatible release\n');
console.log('既存workflow保持・権限拡大なしのソース取り込み・次版の明示base追従の回帰試験成功');
